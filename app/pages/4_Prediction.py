"""Early warning & self-control for one-stage PN/A (thesis module)."""

import io

import pandas as pd
import streamlit as st

from core.ui.page_init import bootstrap_page, finish_page

bootstrap_page(__file__, "prediction", "Early Warning & Self-Control")

from core.constants import PNA_NO3_PER_NH4_REMOVED  # noqa: E402
from core.early_warning import (  # noqa: E402
    EarlyWarningConfig,
    first_detection_day,
    normalize_columns,
    run_early_warning,
    template_dataframe,
)
from core.self_control import ControllerSettings, PIController, recommend_rules, synthetic_nob_outbreak  # noqa: E402

st.title("Early Warning & Self-Control — one-stage PN/A")
st.caption(
    "Rules (stoichiometry) + statistics (EWMA, Hotelling T²) + trend forecast → status and a proposed "
    "aeration change. Decision support only: every action must be confirmed by the operator."
)

with st.expander("How it works / 工作原理", expanded=False):
    st.markdown(
        f"""
**Key indicator — ΔNO₃/ΔNH₄.** In one-stage PN/A, AOB oxidise 1.32 NH₄ to NO₂ for every NH₄ used by
anammox, so NH₄ removed = 2.32 and NO₃ produced = 0.26 → **ΔNO₃/ΔNH₄ ≈ {PNA_NO3_PER_NH4_REMOVED:.2f}**
(Strous et al., 1998). Values rising above ~0.15 indicate NOB growth; effluent NO₂ build-up means
nitritation outruns anammox (often too much oxygen or anammox inhibition).

1. **Rules** — literature thresholds on ΔNO₃/ΔNH₄, effluent NO₂, residual NH₄, TIN removal.
2. **Statistics** — EWMA control charts per indicator and Hotelling T² across indicators,
   against a baseline of stable days (the first *n* days).
3. **Forecast** — local linear trend → days until the warning/alarm threshold (**lead time**).
4. **Self-control** — rule-based or PI supervisory controller proposing a new DO set-point.
"""
    )

source = st.radio(
    "Data source",
    ["Upload file", "Reactor Operation Log (loaded)", "Demo — synthetic NOB outbreak"],
    horizontal=True,
)

raw = None
if source == "Upload file":
    tpl = template_dataframe()
    st.download_button("Download CSV template", tpl.to_csv(index=False).encode(), "pna_daily_template.csv", "text/csv")
    up = st.file_uploader("Daily data (CSV or Excel)", type=["csv", "xlsx", "xls"])
    if up is not None:
        try:
            raw = pd.read_csv(up) if up.name.lower().endswith(".csv") else pd.read_excel(io.BytesIO(up.read()))
        except Exception as exc:  # pragma: no cover - UI feedback
            st.error(f"Could not read file: {exc}")
elif source == "Reactor Operation Log (loaded)":
    res = st.session_state.get("operation_log_result")
    if res is None:
        st.info("Load a log on the Reactor Operation Log page first.")
    else:
        raw = res.df
        st.caption(f"Using: {res.source_name} ({len(raw)} rows)")
else:
    st.warning("SYNTHETIC data generated by the mechanistic model (aeration fault from day 30). "
               "For demonstration and testing only — not laboratory data.")
    if "ew_demo" not in st.session_state:
        with st.spinner("Generating demo data…"):
            st.session_state["ew_demo"] = synthetic_nob_outbreak()
    raw = st.session_state["ew_demo"]

with st.expander("Thresholds & settings"):
    c1, c2, c3 = st.columns(3)
    cfg = EarlyWarningConfig(
        no3_ratio_warning=c1.number_input("ΔNO₃/ΔNH₄ warning", 0.05, 1.0, 0.15, 0.01),
        no3_ratio_alarm=c1.number_input("ΔNO₃/ΔNH₄ alarm", 0.05, 1.0, 0.20, 0.01),
        no2_warning=c2.number_input("Effluent NO₂ warning (mg N/L)", 1.0, 200.0, 20.0, 1.0),
        no2_alarm=c2.number_input("Effluent NO₂ alarm (mg N/L)", 1.0, 300.0, 50.0, 1.0),
        tin_removal_warning=c3.number_input("TIN removal warning (%)", 10.0, 95.0, 60.0, 1.0),
        baseline_days=int(c3.number_input("Baseline (stable) days", 5, 60, 14, 1)),
    )

if raw is None:
    finish_page()
    st.stop()

data = normalize_columns(raw)
if data.empty or not {"nh4_in", "nh4_out", "no3_out"}.issubset(data.columns):
    st.error("Required columns: nh4_in, nh4_out, no3_out (plus optional no2_*, no3_in, do, ph, temperature, hrt_h). "
             "Download the template for the expected format.")
    st.dataframe(raw.head())
    finish_page()
    st.stop()

try:
    result = run_early_warning(data, cfg)
except ValueError as exc:
    st.error(str(exc))
    finish_page()
    st.stop()

d = result.data
last = d.iloc[-1]
banner = {"normal": st.success, "watch": st.info, "warning": st.warning, "alarm": st.error}[result.status]
banner(f"Status on day {last['day']:.0f}: **{result.status.upper()}** — risk score {result.risk_score:.0f}/100")
for r in result.reasons:
    st.write("•", r)

m1, m2, m3, m4 = st.columns(4)
m1.metric("TIN removal", f"{last['tin_removal_pct']:.1f} %" if pd.notna(last["tin_removal_pct"]) else "—")
m2.metric("ΔNO₃/ΔNH₄", f"{last['no3_ratio']:.3f}" if pd.notna(last["no3_ratio"]) else "—",
          help=f"Theory ≈ {PNA_NO3_PER_NH4_REMOVED:.3f}")
m3.metric("Effluent NO₂", f"{last['no2_out']:.1f} mg N/L")
m4.metric("NRR", f"{last['nrr']:.3f} kg N/m³/d" if pd.notna(last["nrr"]) else "— (add hrt_h)")

st.subheader("ΔNO₃/ΔNH₄ vs thresholds")
chart = d[["day", "no3_ratio"]].copy()
chart["theory 0.11"] = cfg.no3_ratio_target
chart["warning"] = cfg.no3_ratio_warning
chart["alarm"] = cfg.no3_ratio_alarm
st.line_chart(chart.set_index("day"))

c1, c2 = st.columns(2)
with c1:
    st.subheader("TIN removal (%)")
    cols = ["tin_removal_pct"] + [c for c in ("tin_removal_pct_ewma", "tin_removal_pct_lcl") if c in d.columns]
    st.line_chart(d.set_index("day")[cols])
with c2:
    st.subheader("Effluent N (mg N/L)")
    st.line_chart(d.set_index("day")[["nh4_out", "no2_out", "no3_out"]])

if "t2" in d.columns:
    st.subheader("Multivariate monitoring — Hotelling T²")
    st.line_chart(d.set_index("day")[["t2", "t2_limit"]])
elif "note" in result.baseline:
    st.caption(result.baseline["note"])

st.subheader("Signals")
if result.signals:
    sig = pd.DataFrame([s.__dict__ for s in result.signals]).sort_values(["day", "level"])
    st.dataframe(sig, use_container_width=True, hide_index=True)
    fd = first_detection_day(result, "watch")
    fa = first_detection_day(result, "alarm")
    if fd is not None and fa is not None:
        st.caption(f"First early signal on day {fd:.0f}; first alarm on day {fa:.0f} → lead time {fa - fd:.0f} d.")
else:
    st.write("No signals.")

if result.forecast:
    st.subheader("Trend forecast (last days)")
    st.json(result.forecast)

st.divider()
st.subheader("Self-control — proposed aeration change")
c1, c2, c3 = st.columns(3)
do_now = c1.number_input("Current DO set-point (mg/L)",
                         0.0, 3.0, float(last["do"]) if pd.notna(last.get("do")) else 0.3, 0.05)
af_now = c2.slider("Aerobic fraction of cycle", 0.1, 1.0, 1.0, 0.05)
strategy = c3.selectbox("Strategy", ["rules", "pi"], format_func=lambda s: "Expert rules" if s == "rules" else "PI (NH₄ + NO₃ ratio)")
latest = {"no3_ratio": float(last["no3_ratio"]) if pd.notna(last["no3_ratio"]) else None,
          "no2_out": float(last["no2_out"]), "nh4_out": float(last["nh4_out"])}
settings = ControllerSettings()
act = recommend_rules(latest, do_now, af_now, settings) if strategy == "rules" else PIController(settings).step(latest, do_now)
st.metric("Proposed DO set-point", f"{act.do_setpoint:.2f} mg/L", f"{act.do_setpoint - do_now:+.2f}")
if act.aeration_fraction < af_now:
    st.metric("Proposed aerobic fraction", f"{act.aeration_fraction:.0%}")
for r in act.rationale:
    st.write("•", r)
for o in act.other_actions:
    st.write("→", o)
st.caption("⚠️ Operator confirmation required. Test controller changes on the PN/A Digital Twin page first.")

finish_page()
